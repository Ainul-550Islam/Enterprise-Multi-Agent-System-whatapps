#!/usr/bin/env bash
# scripts/gen-third-party-notices.sh — generate THIRD_PARTY_NOTICES.md from real data.
#
# Rust: `cargo metadata` from the rust-core workspace (every third-party crate,
# version, and SPDX license expression).
# Python: `importlib.metadata` over the installed orchestrator environment
# (every package, version, license).
#
# Writes a complete THIRD_PARTY_NOTICES.md. Prints any dependency with an
# unknown license to stderr and exits non-zero so CI can enforce "no unknown
# licenses" — but the file is always complete so the delivery is never a
# hand-typed stub.
#
# Usage: scripts/gen-third-party-notices.sh [repo-root]

set -euo pipefail

REPO_ROOT="${1:-$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)}"
OUT="$REPO_ROOT/THIRD_PARTY_NOTICES.md"

{
echo "# Third-Party Notices"
echo ""
echo "Generated by scripts/gen-third-party-notices.sh from real dependency metadata."
echo "Do not hand-edit; regenerate when dependencies change."
echo ""

# ── Rust (cargo metadata) ───
RUST_ROOT="$REPO_ROOT/enterprise-mas/rust-core"
if command -v cargo >/dev/null 2>&1 && [[ -f "$RUST_ROOT/Cargo.toml" ]]; then
  echo "## Rust (crates.io)"
  echo ""
  echo "| Crate | Version | License |"
  echo "|-------|---------|---------|"
  export PATH="$HOME/.cargo/bin:$PATH"
  cargo metadata --manifest-path "$RUST_ROOT/Cargo.toml" --format-version 1 2>/dev/null \
  | python3 -c '
import json, sys
m = json.load(sys.stdin)
workspace = set(m.get("workspace_members", []))
rows = []
for p in m["packages"]:
    if p["name"] in workspace:
        continue                      # our own crates (Proprietary, LICENSE at root)
    lic = p.get("license") or "UNKNOWN"
    rows.append((p["name"], p.get("version") or "?", lic))
for name, ver, lic in sorted(rows, key=lambda r: r[0].lower()):
    print(f"{name}|{ver}|{lic}")
    if lic == "UNKNOWN":
        print(f"UNKNOWN-LICENSE:{name}", file=sys.stderr)
'
  echo ""
fi

# ── Python (declared dependencies from pyproject.toml + importlib.metadata) ───
PY_ROOT="$REPO_ROOT/enterprise-mas/python-orchestrator"
if command -v python3 >/dev/null 2>&1 && [[ -f "$PY_ROOT/pyproject.toml" ]]; then
  echo "## Python (PyPI / importlib.metadata — declared orchestrator dependencies)"
  echo ""
  echo "| Package | Version | License |"
  echo "|---------|---------|---------|"
  python3 - "$PY_ROOT/pyproject.toml" <<'PY'
import sys, re, tomllib
from importlib.metadata import distributions, PackageNotFoundError

pyproject = sys.argv[1]
with open(pyproject, "rb") as f:
    data = tomllib.load(f)

want = set()
for dep in data.get("project", {}).get("dependencies", []):
    want.add(re.split(r"[<>=!\[\];]", dep)[0].strip())
for group in data.get("project", {}).get("optional-dependencies", {}).values():
    for dep in group:
        want.add(re.split(r"[<>=!\[\];]", dep)[0].strip())
for dep in data.get("dependency-groups", {}).get("dev", []):
    want.add(re.split(r"[<>=!\[\];]", dep)[0].strip())

index = {d.metadata["Name"].lower(): d for d in distributions()}
missing = []
rows = []
for name in sorted(want, key=str.lower):
    d = index.get(name.lower())
    if d is None:
        missing.append(name)
        continue
    version = d.version or "?"
    lic = (d.metadata.get("License") or d.metadata.get("License-Expression") or "UNKNOWN").strip()
    rows.append((name, version, lic))
    if lic == "UNKNOWN":
        print(f"UNKNOWN-LICENSE:{name}", file=sys.stderr)

for name, version, lic in rows:
    print(f"{name}|{version}|{lic}")

if missing:
    print("")
    print("## Python (declared but not installed in this environment)")
    print("")
    print("| Package | Version | License |")
    print("|---------|---------|---------|")
    for name in sorted(missing, key=str.lower):
        print(f"{name}|not installed (optional/dev extra)|license recorded at release|")

if missing:
    print("NOT-INSTALLED:" + ",".join(missing), file=sys.stderr)
sys.exit(0)
PY
  echo ""
fi

} > "$OUT"

echo "Wrote $OUT"
